import { readFileSync } from "node:fs";
import { extname, join } from "node:path";
import { addedLines } from "../lib/checks.mjs";

const HASH = /^\s*#(?!!)(?!\s*(type:|noqa|pragma|fmt:|pylint:|mypy:|ruff:|-\*-))/;
const SLASH = /^\s*(\/\/(?!\s*(eslint|@ts-|prettier|biome|istanbul|#|go:|nolint|\+build|export\s))|\/\*(?!\s*(eslint|@ts-|istanbul|webpackChunk)))/;
const STYLE = { ".py": HASH, ".pyi": HASH, ".ts": SLASH, ".tsx": SLASH, ".js": SLASH, ".jsx": SLASH, ".mjs": SLASH, ".cjs": SLASH, ".java": SLASH, ".kt": SLASH, ".go": SLASH, ".rs": SLASH };

export function run({ root, changed, noComments }) {
  if (!noComments) return [];
  const findings = [];
  for (const rel of changed) {
    const re = STYLE[extname(rel)];
    if (!re || generated(join(root, rel))) continue;
    const added = addedLines(root, rel).filter((l) => re.test(l.text));
    if (added.length) findings.push({ class: "lint", file: `${rel}:${added[0].line}`, message: `${rel}:${added[0].line}: ${added.length} new comment lines, for example “${added[0].text.trim().slice(0, 60)}”. Code carries no comments; facts go in the README` });
  }
  return findings;
}

const GENERATED = /auto-?generated|@generated|code generated by|do not (edit|modify|make direct changes)/i;

export function generated(path) {
  try {
    return GENERATED.test(readFileSync(path, "utf8").slice(0, 600));
  } catch {
    return false;
  }
}
